macro_rules! nt_sysnos {
    ($(($number:literal, $name:ident)),+ $(,)?) => {
        /// Stable LiteBox syscall numbers for NT syscalls handled by the Windows shim.
        ///
        /// Rewritten guest PE stubs load these numbers into `eax` instead of the
        /// guest ntdll's build-specific syscall numbers. The values follow the
        /// Windows default ordering so generated traces and hand-written test
        /// stubs remain easy to compare with common syscall tables.
        #[allow(clippy::enum_variant_names)]
        #[derive(Clone, Copy, Debug, Eq, PartialEq)]
        #[repr(u32)]
        pub enum NtSysno {
            $($name = $number,)+
        }

        impl NtSysno {
            #[must_use]
            pub const fn from_raw(raw: usize) -> Option<Self> {
                match raw {
                    $($number => Some(Self::$name),)+
                    _ => None,
                }
            }

            #[must_use]
            pub fn from_export_name(name: &str) -> Option<Self> {
                match name {
                    $(stringify!($name) => Some(Self::$name),)+
                    _ => None,
                }
            }

            #[must_use]
            pub const fn as_raw(self) -> u32 {
                self as u32
            }
        }
    };
}

